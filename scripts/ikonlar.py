def _rects(art: str) -> list[tuple[int, int, int]]:
    """Satır başına yatay koşuları (x, y, genişlik) döndürür."""
    rows = [r for r in art.strip("\n").splitlines()]
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        raise ValueError("Her ikon tam 16×16 olmalı.")
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < 16:
            if row[x] == "#":
                start = x
                while x < 16 and row[x] == "#":
                    x += 1
                out.append((start, y, x - start))
            else:
                x += 1
    return out


def svg(name: str, title: str, art: str) -> str:
    rects = "".join(f'<rect x="{x}" y="{y}" width="{w}" height="1"/>' for x, y, w in _rects(art))
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16" '
        f'fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">'
        f"<title>{title}</title>{rects}</svg>\n"
    )


def sprite() -> str:
    parts = [
        '<svg xmlns="http://www.w3.org/2000/svg">'
    ]
    for name, (title, art) in ICONS.items():
        rects = "".join(f'<rect x="{x}" y="{y}" width="{w}" height="1"/>' for x, y, w in _rects(art))
        parts.append(
            f'<symbol id="i-{name}" viewBox="0 0 16 16" fill="currentColor">'
            f"<title>{title}</title>{rects}</symbol>"
        )
    parts.append("</svg>\n")
    return "".join(parts)


def _outputs() -> dict[str, str]:
    """Göreli yol → içerik: ikon/*.svg ve ikonlar.svg."""
    files = {f"ikon/{name}.svg": svg(name, title, art) for name, (title, art) in ICONS.items()}
    files["ikonlar.svg"] = sprite()
    return files


def main(argv: list[str] | None = None) -> int:
    root = Path(__file__).resolve().parents[1] / "src" / "kolaymetin" / "web" / "static"
    parser = argparse.ArgumentParser(
        prog="ikonlar.py",
        description="Piksel ikonları (ikon/*.svg) ve ikon kümesini (ikonlar.svg) üretir.",
        add_help=False,
    )
    parser.add_argument("hedef", nargs="?", type=Path, default=root,
                        help="Çıktı klasörü (varsayılan: src/kolaymetin/web/static).")
    parser.add_argument("--kontrol", action="store_true",
                        help="Dosya yazma; üretilmiş dosyalar güncel mi diye bak (güncel değilse çıkış kodu 1).")
    parser.add_argument("-h", "--yardim", "--help", action="help", help="Bu yardımı göster.")
    args = parser.parse_args(argv)
    out: Path = args.hedef
    files = _outputs()
    if args.kontrol:
        stale = [rel for rel, text in files.items()
                 if not (out / rel).is_file() or (out / rel).read_text(encoding="utf-8") != text]
        for rel in stale:
            print(f"Güncel değil: {out / rel}")
        if not stale:
            print(f"{len(files)} dosya güncel.")
        return 1 if stale else 0
    (out / "ikon").mkdir(parents=True, exist_ok=True)
    for rel, text in files.items():
        (out / rel).write_text(text, encoding="utf-8")
    print(f"{len(ICONS)} ikon yazıldı: {out / 'ikon'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
